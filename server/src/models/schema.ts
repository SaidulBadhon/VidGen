export const materialSourceInfoSchema = z
  .object({
    provider: z.string().optional(),
    search_term: z.string().optional(),
    asset_id: z.string().nullable().optional(),
    source_page: z.string().nullable().optional(),
    creator: z
      .object({
        id: z.string().optional(),
        name: z.string().optional(),
        profile_page: z.string().optional(),
      })
      .nullable()
      .optional(),
    rendition: z
      .object({
        id: z.string().nullable().optional(),
        width: z.number().nullable().optional(),
        height: z.number().nullable().optional(),
      })
      .nullable()
      .optional(),
  })
  .passthrough();

export const materialInfoSchema = z.object({
  provider: z.string().default("pexels"),
  url: z.string().default(""),
  duration: z.number().default(0),
  /**
   * Filtered public provenance for a downloaded asset. Rebuilt from a field
   * allow-list before being persisted so signed URLs and credentials supplied
   * by a caller never reach the task record.
   */
  source_info: materialSourceInfoSchema.nullish(),
});
export type MaterialInfo = z.infer<typeof materialInfoSchema>;

