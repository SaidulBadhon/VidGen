export const VideoConcatMode = {
  random: "random",
  sequential: "sequential",
} as const;
export type VideoConcatModeValue = (typeof VideoConcatMode)[keyof typeof VideoConcatMode];

export const VideoTransitionMode = {
  none: null,
  shuffle: "Shuffle",
  fadeIn: "FadeIn",
  fadeOut: "FadeOut",
  slideIn: "SlideIn",
  slideOut: "SlideOut",
  zoomIn: "ZoomIn",
  zoomOut: "ZoomOut",
} as const;
export type VideoTransitionModeValue =
  | "Shuffle"
  | "FadeIn"
  | "FadeOut"
  | "SlideIn"
  | "SlideOut"
  | "ZoomIn"
  | "ZoomOut"
  | null;

export const VideoAspect = {
  landscape: "16:9",
  portrait: "9:16",
  square: "1:1",
} as const;
export type VideoAspectValue = (typeof VideoAspect)[keyof typeof VideoAspect];

export function aspectToResolution(aspect: VideoAspectValue): [number, number] {
  switch (aspect) {
    case VideoAspect.landscape:
      return [1920, 1080];
    case VideoAspect.portrait:
      return [1080, 1920];
    case VideoAspect.square:
      return [1080, 1080];
    default:
      throw new Error(`unsupported video aspect: ${aspect}`);
  }
}

/** Orientation name used by the Pexels search API. */
export function aspectOrientation(aspect: VideoAspectValue): "landscape" | "portrait" | "square" {
  if (aspect === VideoAspect.landscape) return "landscape";
  if (aspect === VideoAspect.portrait) return "portrait";
  return "square";
}

